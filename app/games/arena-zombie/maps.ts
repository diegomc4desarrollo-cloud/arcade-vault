export interface ParsedFloor {
  map: FloorMap;
  tileW: number;
  tileH: number;
  walls: Obstacle[];            // muros ya fusionados en tramos horizontales (menos rects = menos colisiones)
  solid: boolean[][];           // [fila][col] true si es muro — lo usa el flow field
  playerSpawn: { x: number; y: number };
  zombieSpawns: { x: number; y: number }[];
  pickupSpots: { x: number; y: number }[];
}

/** Convierte una planta en obstáculos y puntos absolutos para el tamaño actual de la arena. */
export function parseFloor(map: FloorMap, W: number, H: number): ParsedFloor {
  const tileW = W / MAP_COLS, tileH = H / MAP_ROWS;
  const center = (c: number, r: number) => ({ x: (c + 0.5) * tileW, y: (r + 0.5) * tileH });
  const solid: boolean[][] = map.rows.map(row => [...row].map(ch => ch === '#'));
  const walls: Obstacle[] = [];
  let playerSpawn = center(MAP_COLS / 2, MAP_ROWS / 2);
  const zombieSpawns: { x: number; y: number }[] = [];
  const pickupSpots: { x: number; y: number }[] = [];

  for (let r = 0; r < MAP_ROWS; r++) {
    let c = 0;
    while (c < MAP_COLS) {
      const ch = map.rows[r][c];
      if (ch === '#') {
        let end = c;
        while (end + 1 < MAP_COLS && map.rows[r][end + 1] === '#') end++;
        walls.push({ x: c * tileW, y: r * tileH, w: (end - c + 1) * tileW, h: tileH });
        c = end + 1;
        continue;
      }
      if (ch === 'P') playerSpawn = center(c, r);
      else if (ch === 'S') zombieSpawns.push(center(c, r));
      else if (ch === 'W') pickupSpots.push(center(c, r));
      c++;
    }
  }
  return { map, tileW, tileH, walls, solid, playerSpawn, zombieSpawns, pickupSpots };
}

/** Planta (0-based) que corresponde a una oleada (1-based). Se queda en la última si se pasa. */
export function floorIndexForWave(wave: number): number {
  return Math.min(Math.floor((wave - 1) / WAVES_PER_FLOOR), FLOOR_MAPS.length - 1);
}

/** true cuando la oleada recién superada era la última de la planta 10. */
export function isBuildingCleared(wave: number): boolean {
  return wave >= FLOOR_MAPS.length * WAVES_PER_FLOOR;
}
